def _ink(r, g, b, a=1.0):
    return (r / 255, g / 255, b / 255, a)


class Ink:
    BG = _ink(9, 9, 9)
    ON = _ink(242, 242, 237)
    MID = _ink(179, 179, 173)
    DIM = _ink(117, 117, 115)
    OFF = _ink(38, 38, 38)
    LINE = _ink(48, 48, 48)

    @staticmethod
    def alpha(c, a):
        """A shade of `c` at the given opacity (multiplied with its own)."""
        return (c[0], c[1], c[2], c[3] * max(0.0, min(1.0, a)))


def has(ch):
    return ch in GLYPHS


def width(text, scale):
    return max(len(text) * 6 - 1, 0) * scale


def rect(dc, color, x, y, w, h):
    if dc is not None and w > 0 and h > 0:
        dc.set_source_rgba(*color)
        dc.rectangle(x, y, w, h)
        dc.fill()


def draw(dc, text, x, y, scale, color):
    if dc is None or not text:
        return
    dot = scale - 0.75 if scale >= 3 else scale
    for i, ch in enumerate(text.upper()):
        rows = GLYPHS.get(ch)
        if rows is None:
            continue
        ox = x + i * 6 * scale
        for r, bits in enumerate(rows):
            for c in range(5):
                if bits & (0x10 >> c):
                    dc.rectangle(ox + c * scale, y + r * scale, dot, dot)
    dc.set_source_rgba(*color)
    dc.fill()


def draw_right(dc, text, right, y, scale, color):
    draw(dc, text, right - width(text, scale), y, scale, color)


def round_rect(dc, x, y, w, h, r):
    dc.new_sub_path()
    dc.arc(x + w - r, y + r, r, -1.5707963, 0)
    dc.arc(x + w - r, y + h - r, r, 0, 1.5707963)
    dc.arc(x + r, y + h - r, r, 1.5707963, 3.1415926)
    dc.arc(x + r, y + r, r, 3.1415926, 4.7123889)
    dc.close_path()
